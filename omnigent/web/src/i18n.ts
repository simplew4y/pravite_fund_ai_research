import i18n from "i18next";
import { initReactI18next } from "react-i18next";

export const APP_LOCALES = ["zh-CN", "en-US"] as const;
export type AppLocale = (typeof APP_LOCALES)[number];

export const APP_LOCALE_STORAGE_KEY = "omnigent.locale";
export const APP_LOCALE_CHANGED_EVENT = "omnigent:locale-changed";

export function normalizeAppLocale(value: unknown): AppLocale {
  return value === "en-US" ? "en-US" : "zh-CN";
}

export function readDeviceLocale(): AppLocale {
  try {
    return normalizeAppLocale(window.localStorage.getItem(APP_LOCALE_STORAGE_KEY));
  } catch {
    return "zh-CN";
  }
}

export async function applyAppLocale(locale: AppLocale): Promise<void> {
  try {
    window.localStorage.setItem(APP_LOCALE_STORAGE_KEY, locale);
  } catch {
    // Locale persistence is best-effort; the current page still updates.
  }
  document.documentElement.lang = locale;
  await i18n.changeLanguage(locale);
  window.dispatchEvent(new CustomEvent(APP_LOCALE_CHANGED_EVENT, { detail: { locale } }));
}

